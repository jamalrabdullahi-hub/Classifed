/**
 * Signs and submits what the risk service has already accepted.
 *
 * This module, `@flt/core/security/agent-keys`, and the agent's key columns
 * are the only places in the whole codebase a private key exists outside a
 * participant's own browser. Everything that reaches here has already been
 * validated against the participant's stored configuration — this file's
 * only job is turning an accepted decision into a signed transaction, and
 * recording exactly what happened whether it succeeds or not.
 */

/** One wallet row per (agent, venue) pair, standing in for the agent's own address. */
async function agentWallet(userId: string, venueSlug: string, address: Address, chainId: number) {
  const existing = await prisma.wallet.findFirst({
    where: { userId, address: address.toLowerCase(), chainId },
  });
  if (existing) return existing;

  return prisma.wallet.create({
    data: {
      id: newId(),
      userId,
      address,
      chainId,
      label: `AI agent (${venueSlug})`,
      connector: 'agent',
      // Generated by FLT, not linked by a signature — "verified" here means
      // "this server controls the key", which is true by construction rather
      // than by the usual ownership proof.
      verifiedAt: new Date(),
    },
  });
}

function requireKey(keys: AgentSigningKey[], venueSlug: string): AgentSigningKey {
  const key = keys.find((k) => k.venueSlug === venueSlug);
  if (!key || !key.authorizedAt) {
    throw new ValidationError(`No authorised ${venueSlug} key for this agent.`);
  }
  return key;
}

export interface ExecutionOutcome {
  action: 'OPEN' | 'CLOSE' | 'HOLD' | 'REJECTED';
  accepted: boolean;
  rejectionReason: string | null;
  orderId: string | null;
}

/**
 * Validates and, if accepted, executes one decision on one venue.
 *
 * A HOLD or a rejection never reaches a venue at all — this function's first
 * job is deciding whether to touch the network, not just how.
 */
export async function executeAgentDecision(params: {
  user: User;
  agent: TradingAgent;
  keys: AgentSigningKey[];
  venueSlug: 'hyperliquid' | 'ostium';
  decision: DeepSeekDecision;
}): Promise<ExecutionOutcome> {
  const { user, agent, keys, venueSlug, decision } = params;

  const candidate: AgentDecisionCandidate = {
    action: decision.action,
    symbol: decision.symbol,
    side: decision.side,
    leverage: decision.leverage,
    usdNotional: decision.usdNotional !== undefined ? String(decision.usdNotional) : undefined,
    reasoning: decision.reasoning,
  };

  if (candidate.action === 'HOLD') {
    return { action: 'HOLD', accepted: true, rejectionReason: null, orderId: null };
  }

  const allocatedUsd =
    venueSlug === 'hyperliquid' ? agent.allocatedUsdHyperliquid : agent.allocatedUsdOstium;

  const check = validateAgentDecision(candidate, agent, allocatedUsd);
  if (!check.ok) {
    return { action: 'REJECTED', accepted: false, rejectionReason: check.reason, orderId: null };
  }

  if (agent.status !== TradingAgentStatus.ACTIVE) {
    return {
      action: 'REJECTED',
      accepted: false,
      rejectionReason: `Agent is ${agent.status.toLowerCase()}, not active.`,
      orderId: null,
    };
  }

  const venue = perpVenueBySlug(venueSlug);
  if (!venue) {
    return { action: 'REJECTED', accepted: false, rejectionReason: 'Venue not configured.', orderId: null };
  }

  const key = requireKey(keys, venueSlug);
  const privateKey = decryptPrivateKey({
    ciphertext: key.ciphertext,
    iv: key.iv,
    authTag: key.authTag,
    keyVersion: key.keyVersion,
  });

  try {
    const wallet = await agentWallet(
      user.id,
      venueSlug,
      key.address as Address,
      venue.settlementChainId,
    );

    if (candidate.action === 'CLOSE') {
      const { order, action } = await prepareClose(venue, {
        user,
        wallet,
        symbol: candidate.symbol,
        size: null,
        slippageBps: 50,
      });
      const venueOrderId = await submitPrepared(venueSlug, privateKey, action);
      await recordSubmission({ orderId: order.id, userId: user.id, venueOrderId });
      await auditOrder(user.id, order.id, 'CLOSE');
      return { action: 'CLOSE', accepted: true, rejectionReason: null, orderId: order.id };
    }

    // OPEN. Mandatory protection is enforced here, not left to the model to
    // remember to ask for — see TradingAgent.protectionRequired.
    //
    // Dollars are converted to contracts here, against this server's own mark
    // price, for the same reason the manual-order route does it server-side:
    // the model reasons in dollars, but the position that actually reaches
    // the venue must never be worth more than the allocation it was checked
    // against above.
    const market = await venue.getMarket(candidate.symbol);
    if (!market?.markPrice) {
      throw new ValidationError(`${venueSlug} is not quoting ${candidate.symbol}.`);
    }
    const size = contractsForUsd(
      new Decimal(candidate.usdNotional!),
      new Decimal(market.markPrice),
      market.sizeDecimals,
    ).toFixed();

    const { order, action } = await prepareOpen(venue, {
      user,
      wallet,
      intent: {
        symbol: candidate.symbol,
        side: candidate.side!,
        size,
        leverage: candidate.leverage!,
        marginMode: 'ISOLATED',
        orderType: 'MARKET',
        limitPrice: null,
        triggerPrice: null,
        takeProfitPrice: null,
        stopLossPrice: null,
        slippageBps: 50,
        reduceOnly: false,
      },
    });

    const venueOrderId = await submitPrepared(venueSlug, privateKey, action);
    await recordSubmission({ orderId: order.id, userId: user.id, venueOrderId });
    await auditOrder(user.id, order.id, 'OPEN');

    if (agent.protectionRequired) {
      await attachProtection({ user, wallet, venue, privateKey, symbol: candidate.symbol, side: candidate.side!, leverage: candidate.leverage!, usdNotional: new Decimal(candidate.usdNotional!) });
    }

    return { action: 'OPEN', accepted: true, rejectionReason: null, orderId: order.id };
  } catch (error) {
    // A failure this deep — the venue rejected the order, the RPC timed out,
    // a signature failed — is exactly the kind of thing that should stop the
    // agent rather than retry blind on the next tick.
    await killSwitchAgent(
      agent.id,
      `Execution failed on ${venueSlug}: ${error instanceof Error ? error.message : String(error)}`,
    );
    return {
      action: 'REJECTED',
      accepted: false,
      rejectionReason: error instanceof Error ? error.message : 'Execution failed.',
      orderId: null,
    };
  }
}

async function auditOrder(userId: string, orderId: string, kind: 'OPEN' | 'CLOSE') {
  await audit(prisma, {
    action: AuditAction.AGENT_TRADING_ORDER_SUBMITTED,
    actorType: 'SYSTEM',
    actorUserId: userId,
    entityType: 'perp_order',
    entityId: orderId,
    after: { kind },
  });
}


/**
 * Buys protection for a position the agent just opened, paid from the same
 * agent-controlled wallet, signed by the same key.
 */
async function attachProtection(params: {
  user: User;
  wallet: Awaited<ReturnType<typeof agentWallet>>;
  venue: PerpVenue;
  privateKey: Hex;
  symbol: string;
  side: 'LONG' | 'SHORT';
  leverage: number;
  usdNotional: Decimal;
}) {
  const { user, wallet, venue, privateKey, symbol, side, leverage, usdNotional } = params;

  const prepared = await preparePurchase(
    venue,
    { user, wallet },
    {
      kind: 'BASE_DAY',
      symbol,
      side,
      usdNotional,
      leverage,
      percentile: 0.95,
    },
  );

  const account = privateKeyToAccount(privateKey);
  const client = createWalletClient({
    account,
    chain: undefined,
    transport: http(env().BASE_RPC_URL),
  }).extend(publicActions);

  const hashes = new Map<'contribution' | 'operator-fee', `0x${string}`>();
  for (const transfer of prepared.transfers) {
    const hash = await client.sendTransaction({
      chain: undefined,
      to: transfer.to as Address,
      data: transfer.data,
    });
    await client.waitForTransactionReceipt({ hash });
    hashes.set(transfer.purpose, hash);
  }

  const contributionHash = hashes.get('contribution');
  const operatorFeeHash = hashes.get('operator-fee');
  if (!contributionHash || !operatorFeeHash) {
    throw new ValidationError('Protection premium transfers did not complete.');
  }

  await confirmPurchase(prepared.policyId, user, {
    poolTxHash: contributionHash,
    operatorTxHash: operatorFeeHash,
  });
}
